            <select class="product"><option value="">Select product…</option></select>
            <div class="error" data-field="product_id"></div>
        </td>
        <td>
            <input class="qty" type="number" min="1" step="1" value="1">
            <div class="error" data-field="quantity"></div>
        </td>
        <td class="num price">—</td>
        <td class="num line-total">—</td>
