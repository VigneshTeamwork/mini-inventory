@push('scripts')
<script>
(() => {
    const DENOMINATIONS = @json(\App\Services\ChangeCalculator::DENOMINATIONS);
    // Generated by Laravel so they include the base path (e.g. /task/public under XAMPP's Apache).
    const ROUTES = {
        products: @json(route('api.products.index')),
        lowStock: @json(route('api.products.low-stock')),
        lookup: @json(route('api.customers.lookup')),
        orders: @json(route('api.orders.store')),
    };
    const $ = (sel, root = document) => root.querySelector(sel);
    const products = new Map();
    const lines = $('#lines');

    // Same integer-paise rules as App\Services\OrderCalculator. Preview only — the server decides.
    const toPaise = (v) => Math.round(parseFloat(v || 0) * 100);
    const money = (p) => '₹' + (p / 100).toFixed(2);
    const lineAmounts = (product, qty) => {
        const subtotal = toPaise(product.price) * qty;
        const tax = Math.floor((subtotal * Math.round(parseFloat(product.tax_percent) * 100) + 5000) / 10000);
        return { subtotal, tax, total: subtotal + tax };
    };

    const api = async (url, options = {}) => {
        const response = await fetch(url, {
            ...options,
            headers: { 'Accept': 'application/json', 'Content-Type': 'application/json', ...(options.headers || {}) },
        });
        let body = null;
        try { body = await response.json(); } catch (e) { /* empty body */ }
        return { status: response.status, ok: response.ok, body };
    };

    function addRow() {
        const row = $('#line-template').content.firstElementChild.cloneNode(true);
        const select = $('.product', row);
        for (const p of products.values()) {
            const option = new Option(`${p.name} (${p.code}) — ₹${p.price} · ${p.stock_on_hand} left`, p.id);
            option.disabled = p.stock_on_hand === 0;
            select.add(option);
        }
        select.addEventListener('change', recalc);
        $('.qty', row).addEventListener('input', recalc);
        $('.remove', row).addEventListener('click', () => { row.remove(); if (!lines.children.length) addRow(); recalc(); });
        lines.appendChild(row);
        select.focus();
    }

    function selectedLines() {
        return [...lines.children]
            .map((row) => ({ row, product: products.get(Number($('.product', row).value)), qty: parseInt($('.qty', row).value, 10) }))
            .filter((l) => l.product);
    }

    function recalc() {
        let subtotal = 0, tax = 0;
        for (const row of lines.children) {
            const product = products.get(Number($('.product', row).value));
            const qty = parseInt($('.qty', row).value, 10);
            if (!product || !(qty > 0)) { $('.price', row).textContent = product ? money(toPaise(product.price)) : '—'; $('.line-total', row).textContent = '—'; continue; }
            const a = lineAmounts(product, qty);
            subtotal += a.subtotal; tax += a.tax;
            $('.price', row).textContent = money(toPaise(product.price));
            $('.line-total', row).textContent = money(a.total);
        }
        const grand = subtotal + tax;
        $('#subtotal').textContent = money(subtotal);
        $('#tax').textContent = money(tax);
        $('#grand-total').textContent = money(grand);

        const tenderedRaw = $('#tendered').value;
        if (tenderedRaw === '' || grand === 0) { $('#balance').textContent = '—'; $('#breakdown').textContent = ''; return; }
        const change = toPaise(tenderedRaw) - grand;
        if (change < 0) { $('#balance').textContent = 'Short by ' + money(-change); $('#breakdown').textContent = ''; return; }
        $('#balance').textContent = money(change);
        let rupees = Math.floor((change + 50) / 100);
        const parts = [];
        for (const d of DENOMINATIONS) { if (rupees >= d) { parts.push(`${Math.floor(rupees / d)}×${d}`); rupees %= d; } }
        $('#breakdown').textContent = parts.length ? '→ ' + parts.join(' + ') : '';
    }

    async function lookupCustomer() {
        const email = $('#email').value.trim();
        const name = $('#name');
        const hint = $('#customer-hint');
        if (!email.includes('@')) { hint.textContent = ''; return; }
        const { status, body } = await api(ROUTES.lookup + '?email=' + encodeURIComponent(email));
        if (status === 200) {
            name.value = body.data.name; name.readOnly = true; name.dataset.autofilled = '1';
            hint.textContent = 'Returning customer';
        } else {
            if (name.dataset.autofilled) { name.value = ''; delete name.dataset.autofilled; }
            name.readOnly = false;
            hint.textContent = 'New customer — please enter a name';
        }
    }

    async function loadLowStock() {
        const { body } = await api(ROUTES.lowStock);
        const list = $('#low-stock');
        list.replaceChildren();
        $('#threshold').textContent = body.meta.threshold;
        if (!body.data.length) { list.append(Object.assign(document.createElement('li'), { textContent: 'All products are well stocked.' })); return; }
        for (const p of body.data) {
            const units = p.stock_on_hand === 1 ? 'unit' : 'units';
            list.append(Object.assign(document.createElement('li'), { textContent: `${p.name} — ${p.stock_on_hand} ${units} left` }));
        }
    }

    function clearErrors() {
        document.querySelectorAll('.error').forEach((el) => { el.textContent = ''; });
        $('#form-error').hidden = true;
    }

    function showErrors(errors, sentRows) {
        const unplaced = [];
        for (const [key, messages] of Object.entries(errors)) {
            const match = key.match(/^items\.(\d+)\.(product_id|quantity)$/);
            const target = match
                ? sentRows[Number(match[1])] && $(`[data-field="${match[2]}"]`, sentRows[Number(match[1])])
                : $(`[data-error="${key}"]`);
            if (target) target.textContent = messages.join(' ');
            else unplaced.push(...messages);
        }
        if (unplaced.length) showFormError(unplaced.join(' '));
    }

    function showFormError(message) {
        const box = $('#form-error');
        box.textContent = message;
        box.hidden = false;
        box.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }

    async function generateBill() {
        clearErrors();
        const chosen = selectedLines();
        if (!chosen.length) { $('[data-error="items"]').textContent = 'Add at least one product.'; return; }

        const payload = {
            customer: { email: $('#email').value.trim(), name: $('#name').value.trim() || null },
            items: chosen.map((l) => ({ product_id: l.product.id, quantity: l.qty })),
        };
        if ($('#tendered').value !== '') payload.amount_tendered = $('#tendered').value;

        const button = $('#generate');
        button.disabled = true; button.textContent = 'Generating…';
        try {
            const { status, body } = await api(ROUTES.orders, { method: 'POST', body: JSON.stringify(payload) });
            if (status === 201) { window.location.href = body.data.bill_url + '?new=1'; return; }
            if (status === 422) { showErrors(body.errors || {}, chosen.map((l) => l.row)); await refreshProducts(); }
            else showFormError((body && body.message) || 'Something went wrong. Please try again.');
        } catch (e) {
            showFormError('Network error. Please try again.');
        } finally {
            button.disabled = false; button.textContent = 'Generate Bill';
        }
    }

    // Keep stock counts in the dropdowns current without losing what the cashier picked.
    async function refreshProducts() {
        const { body } = await api(ROUTES.products);
        body.data.forEach((p) => products.set(p.id, p));
        for (const option of lines.querySelectorAll('option[value]:not([value=""])')) {
            const p = products.get(Number(option.value));
            option.text = `${p.name} (${p.code}) — ₹${p.price} · ${p.stock_on_hand} left`;
            option.disabled = p.stock_on_hand === 0 && !option.selected;
        }
        loadLowStock();
    }

    $('#email').addEventListener('change', lookupCustomer);
    $('#add-row').addEventListener('click', addRow);
    $('#tendered').addEventListener('input', recalc);
    $('#generate').addEventListener('click', generateBill);

    (async () => {
        const { body } = await api(ROUTES.products);
        body.data.forEach((p) => products.set(p.id, p));
        addRow();
        loadLowStock();
    })();
})();
</script>
@endpush
